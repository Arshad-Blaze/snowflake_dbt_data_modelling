CREATE WAREHOUSE DBT_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE RESOURCE MONITOR TRIAL_RM WITH CREDIT_QUOTA = 20
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE DBT_WH SET RESOURCE_MONITOR = TRIAL_RM;

SET my_user = (SELECT CURRENT_USER());
CREATE ROLE DBT_ROLE;
GRANT USAGE ON WAREHOUSE DBT_WH TO ROLE DBT_ROLE
GRANT ROLE DBT_ROLE TO USER IDENTIFIER($my_user);

CREATE DATABASE ANALYTICS;
GRANT ALL ON DATABASE ANALYTICS TO ROLE DBT_ROLE;
USE DATABASE ANALYTICS;
CREATE SCHEMA RAW;
CREATE SCHEMA STAGING;
CREATE SCHEMA INTERMEDIATE;
CREATE SCHEMA MARTS;



